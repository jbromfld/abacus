"""Generate TypeScript contracts from the app's OpenAPI; --check detects drift."""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from abacus.main import app


def type_for(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    for union in ("anyOf", "oneOf", "allOf"):
        if union in schema:
            return (" & " if union == "allOf" else " | ").join(
                "(" + type_for(x) + ")" for x in schema[union]
            )
    kind = schema.get("type")
    if kind == "array":
        return "(" + type_for(schema.get("items", {})) + ")[]"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [
            json.dumps(k) + ("" if k in required else "?") + ": " + type_for(v) + ";"
            for k, v in props.items()
        ]
        extra = schema.get("additionalProperties")
        if extra:
            fields.append(
                "[key: string]: "
                + (
                    type_for(extra)
                    if isinstance(extra, dict) and not props
                    else "unknown"
                )
                + ";"
            )
        return "{ " + " ".join(fields) + " }"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schemas = app.openapi()["components"]["schemas"]
    output = "// Generated by scripts/generate_api_types.py. Do not edit.\n"
    output += (
        "\n".join(
            "export type " + name + " = " + type_for(schema) + ";"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    target = Path(__file__).resolve().parents[1] / "frontend/src/generated/api.ts"
    if args.check:
        if not target.exists() or target.read_text() != output:
            raise SystemExit(
                "API types differ; run .venv/bin/python scripts/generate_api_types.py"
            )
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output)


if __name__ == "__main__":
    main()
